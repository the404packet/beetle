GREEN="\033[0;32m"
CYAN="\033[0;36m"
RESET="\033[0m"

banner="
          ##########        ##########
          ##      ##        ##      ##
          ####    ####    ####    ####      
                    ########                
                    ########                
            ########################        
      ##    ########################          
      ####################################        ██████╗ ███████╗███████╗████████╗██╗     ███████╗
            ########################    ##        ██╔══██╗██╔════╝██╔════╝╚══██╔══╝██║     ██╔════╝
      ##    ########################              ██████╔╝█████╗  █████╗     ██║   ██║     █████╗
      ####################################        ██╔══██╗██╔══╝  ██╔══╝     ██║   ██║     ██╔══╝
            ########################    ##        ██████╔╝███████╗████████╗  ██║   ███████╗███████╗
      ##    ########################              ╚═════╝ ╚══════╝╚═══════╝  ╚═╝   ╚══════╝╚══════╝
      ####################################
            ########################    ##
            ########################
                ################
                  ##        ##       
                  ##        ##  
          +----------------------------+
          |      OS HARDENING TOOL     |
          +----------------------------+
"

while IFS= read -r line; do
    for (( i=0; i<${#line}; i++ )); do
        char="${line:$i:1}"
        if [[ "$char" == "#" ]]; then
            printf "${GREEN}%s${RESET}" "$char"
        else
            printf "${CYAN}%s${RESET}" "$char"
        fi
    done
    printf "\n"
done <<< "$banner"
